/*!
 * Outfitter part: version-badge v1.0.0
 * A small, always-visible-but-out-of-the-way version stamp for any Atlas project.
 *
 * Copy this file into your project (e.g. site/version-badge.js) and add ONE line:
 *   <script src="version-badge.js" defer></script>
 *
 * By default it reads version.json — generated from CHANGELOG.md by the included
 * stamp-version.mjs — so the changelog stays the single source of truth for the
 * version and the badge updates itself on every release.
 *
 * Zero dependencies. Renders in a shadow root, so it cannot collide with your CSS.
 *
 * Part of the Outfitter — outfitter.illuminatedatlas.com
 */
(function () {
  'use strict';

  var PART = 'version-badge';
  var PART_VERSION = '1.0.0';

  var Outfitter = (window.Outfitter = window.Outfitter || {});

  /* ------------------------------------------------------------------ *
   * Corner stack — same few lines as every other Outfitter web part, so
   * two widgets in the same corner stack instead of overlapping. Parts
   * never import each other; they only meet at this global.
   * ------------------------------------------------------------------ */
  function reserveCorner(corner, extent, id) {
    var reg = (window.__outfitterCorners = window.__outfitterCorners || {});
    var list = (reg[corner] = reg[corner] || []);
    var existing = null;
    for (var i = 0; i < list.length; i++) if (list[i].id === id) existing = list[i];
    if (existing) existing.extent = extent;
    else list.push({ id: id, extent: extent });
    var offset = 0;
    for (var j = 0; j < list.length; j++) {
      if (list[j].id === id) break;
      offset += list[j].extent + 8;
    }
    return offset;
  }

  var CSS = [
    ':host{all:initial}',
    '*,*::before,*::after{box-sizing:border-box}',
    ':host{',
    '  --ofv-bg:rgba(20,16,34,.72);--ofv-text:#e8e3f6;--ofv-dim:#a79fc0;',
    '  --ofv-accent:#8b6df0;--ofv-border:rgba(255,255,255,.15);--ofv-radius:8px;',
    '  --ofv-font:ui-monospace,SFMono-Regular,Menlo,Consolas,monospace;',
    '  --ofv-idle-opacity:.42;',
    '}',
    ':host([data-theme="light"]){',
    '  --ofv-bg:rgba(255,255,255,.82);--ofv-text:#241d38;--ofv-dim:#5d5672;',
    '  --ofv-border:rgba(20,12,40,.16);',
    '}',
    // The wrapper is inert; only the chip itself takes clicks, so the game
    // underneath keeps receiving input everywhere else.
    '.wrap{position:fixed;z-index:2147481000;pointer-events:none;',
    '  display:flex;flex-direction:column;gap:6px}',
    '.wrap>*{pointer-events:auto}',
    '.wrap[data-corner$="right"]{align-items:flex-end}',
    '.wrap[data-corner$="left"]{align-items:flex-start}',
    '.wrap[data-corner^="top"]{flex-direction:column-reverse}',

    '.chip{appearance:none;font-family:var(--ofv-font);font-size:11px;line-height:1;',
    '  letter-spacing:.02em;color:var(--ofv-text);background:var(--ofv-bg);',
    '  border:1px solid var(--ofv-border);border-radius:var(--ofv-radius);',
    '  padding:4px 7px;cursor:pointer;opacity:var(--ofv-idle-opacity);',
    '  transition:opacity .18s;backdrop-filter:blur(6px);',
    '  -webkit-tap-highlight-color:transparent;touch-action:manipulation;',
    '  display:inline-flex;align-items:center;gap:5px;max-width:60vw}',
    '.chip:hover,.chip:focus-visible{opacity:1}',
    '.chip:focus-visible{outline:2px solid var(--ofv-accent);outline-offset:2px}',
    '.chip[data-static]{cursor:default}',
    '.dot{width:5px;height:5px;border-radius:50%;background:var(--ofv-accent);flex:none}',
    '.dot[data-env="staging"]{background:#f0b429}',
    '.dot[data-env="local"]{background:#6ddfa0}',
    '.env{color:var(--ofv-dim)}',

    '.card{font-family:system-ui,-apple-system,"Segoe UI",Roboto,sans-serif;font-size:12px;',
    '  color:var(--ofv-text);background:var(--ofv-bg);border:1px solid var(--ofv-border);',
    '  border-radius:10px;padding:9px 11px;backdrop-filter:blur(10px);',
    '  box-shadow:0 8px 26px rgba(0,0,0,.4);max-width:min(280px,calc(100vw - 24px))}',
    '.card[hidden]{display:none}',
    '.row{display:flex;gap:10px;justify-content:space-between;padding:2px 0}',
    '.row dt{color:var(--ofv-dim);margin:0;flex:none}',
    '.row dd{margin:0;text-align:right;font-family:var(--ofv-font);font-size:11px;',
    '  word-break:break-all}',
    'dl{margin:0}',
    '.card a{color:var(--ofv-accent);font-size:11.5px;display:inline-block;margin-top:7px}',
    '.card a:focus-visible{outline:2px solid var(--ofv-accent);outline-offset:2px}',
    '@media (prefers-reduced-motion:reduce){.chip{transition:none}}',
  ].join('\n');

  function create(options) {
    var cfg = Object.assign(
      {
        version: null,          // set it explicitly to skip all detection
        project: null,          // shown in the expanded card
        src: 'version.json',    // generated by stamp-version.mjs; set false to skip
        changelog: null,        // URL the "changelog" link points at
        corner: 'bottom-right',
        theme: 'auto',
        prefix: 'v',
        showEnv: true,          // append "staging"/"local" when not on prod
        expandable: true,       // click to show full build info
        env: null,              // override the auto-detected environment
        container: null,        // element or selector to mount into; default <body>
      },
      options || {}
    );

    var host = document.createElement('div');
    host.setAttribute('data-outfitter-part', PART);
    var root = host.attachShadow({ mode: 'open' });

    var theme = cfg.theme;
    if (theme === 'auto') {
      theme = window.matchMedia && window.matchMedia('(prefers-color-scheme: light)').matches
        ? 'light' : 'dark';
    }
    host.setAttribute('data-theme', theme);

    var style = document.createElement('style');
    style.textContent = CSS;
    root.appendChild(style);

    var wrap = document.createElement('div');
    wrap.className = 'wrap';
    wrap.setAttribute('data-corner', cfg.corner);
    root.appendChild(wrap);

    var card = document.createElement('div');
    card.className = 'card';
    card.hidden = true;
    card.setAttribute('role', 'region');
    card.setAttribute('aria-label', 'Build information');

    var chip = document.createElement('button');
    chip.className = 'chip';
    chip.type = 'button';

    // Order in the DOM decides which sits nearer the screen edge.
    if (cfg.corner.indexOf('top') === 0) {
      wrap.appendChild(chip);
      wrap.appendChild(card);
    } else {
      wrap.appendChild(card);
      wrap.appendChild(chip);
    }

    /* ---------------- environment ---------------- */
    // A version number is only half the answer; "which copy of the site am I
    // looking at" is the other half, and staging-vs-prod confusion is the single
    // most common way people misread a deploy.
    function detectEnv() {
      if (cfg.env) return cfg.env;
      var h = location.hostname;
      if (h === 'localhost' || h === '127.0.0.1' || h.indexOf('.local') > -1) return 'local';
      if (/(^|[.-])staging([.-]|$)/.test(h)) return 'staging';
      return 'prod';
    }
    var env = detectEnv();

    /* ---------------- render ---------------- */
    var info = { version: null, date: null, commit: null, project: cfg.project, env: env };

    function renderChip() {
      var label = info.version ? cfg.prefix + info.version : 'unversioned';
      var envLabel = cfg.showEnv && env !== 'prod' ? env : '';
      chip.innerHTML = '';
      var dot = document.createElement('span');
      dot.className = 'dot';
      dot.setAttribute('data-env', env);
      dot.setAttribute('aria-hidden', 'true');
      chip.appendChild(dot);
      chip.appendChild(document.createTextNode(label));
      if (envLabel) {
        var e = document.createElement('span');
        e.className = 'env';
        e.textContent = envLabel;
        chip.appendChild(e);
      }
      var aria = 'Version ' + (info.version || 'unknown');
      if (envLabel) aria += ', ' + envLabel + ' environment';
      chip.setAttribute('aria-label', aria + (cfg.expandable ? '. Show build details' : ''));
      chip.setAttribute('title', aria);
      if (!cfg.expandable) {
        chip.setAttribute('data-static', '');
        chip.setAttribute('aria-disabled', 'true');
      } else {
        chip.setAttribute('aria-expanded', String(!card.hidden));
      }
    }

    function renderCard() {
      var rows = [];
      if (info.project) rows.push(['project', info.project]);
      rows.push(['version', info.version ? cfg.prefix + info.version : 'unknown']);
      if (info.date) rows.push(['released', info.date]);
      if (info.builtAt) rows.push(['built', info.builtAt.replace('T', ' ').replace(/\..+$/, '')]);
      if (info.commit) rows.push(['commit', info.commit]);
      rows.push(['environment', env]);

      var dl = document.createElement('dl');
      rows.forEach(function (r) {
        var row = document.createElement('div');
        row.className = 'row';
        var dt = document.createElement('dt');
        dt.textContent = r[0];
        var dd = document.createElement('dd');
        dd.textContent = r[1];
        row.appendChild(dt);
        row.appendChild(dd);
        dl.appendChild(row);
      });
      card.innerHTML = '';
      card.appendChild(dl);
      if (cfg.changelog) {
        var a = document.createElement('a');
        a.href = cfg.changelog;
        a.textContent = "What's new →";
        a.target = '_blank';
        a.rel = 'noopener';
        card.appendChild(a);
      }
    }

    function publish() {
      // Other parts (feedback-button) read this instead of duplicating detection.
      if (info.version) Outfitter.version = info.version;
      Outfitter.build = { version: info.version, env: env, commit: info.commit, date: info.date };
      renderChip();
      renderCard();
      place();
    }

    /* ---------------- version detection ---------------- *
     * Order matters: an explicit value always wins, then anything already
     * published on the page, then the stamped file. The badge must never
     * hardcode a version — CHANGELOG.md is the source of truth per
     * PROJECT_STANDARDS §2, and stamp-version.mjs is what carries it here.
     * ------------------------------------------------------------------ */
    function detect() {
      if (cfg.version) {
        info.version = String(cfg.version);
        publish();
        return;
      }
      if (Outfitter.version) {
        info.version = Outfitter.version;
        publish();
        return;
      }
      if (window.__APP_VERSION__) {
        info.version = String(window.__APP_VERSION__);
        publish();
        return;
      }
      var meta = document.querySelector('meta[name="app-version"]');
      if (meta && meta.content) {
        info.version = meta.content.replace(/^v/, '');
        publish();
        return;
      }
      if (cfg.src) {
        // Render immediately so the badge never pops in late, then fill it in.
        publish();
        fetch(cfg.src, { cache: 'no-cache' })
          .then(function (r) { return r.ok ? r.json() : null; })
          .then(function (j) {
            if (!j) return;
            info.version = j.version || info.version;
            info.date = j.date || null;
            info.commit = j.commit || null;
            info.builtAt = j.builtAt || null;
            if (!info.project) info.project = j.project || null;
            if (!cfg.changelog && j.changelog) cfg.changelog = j.changelog;
            publish();
          })
          .catch(function () { /* no version.json — the chip already says so */ });
        return;
      }
      publish();
    }

    /* ---------------- interaction ---------------- */
    if (cfg.expandable) {
      chip.addEventListener('click', function () {
        card.hidden = !card.hidden;
        chip.setAttribute('aria-expanded', String(!card.hidden));
        place();
      });
      // Clicking elsewhere closes it — but the listener is passive about it and
      // never blocks the click from reaching the game.
      document.addEventListener('pointerdown', function (e) {
        if (card.hidden) return;
        if (e.composedPath && e.composedPath().indexOf(host) > -1) return;
        card.hidden = true;
        chip.setAttribute('aria-expanded', 'false');
        place();
      });
    }

    // Keep our clicks and keys away from the host page's own listeners.
    ['pointerdown', 'pointerup', 'mousedown', 'mouseup', 'click', 'keydown', 'keyup', 'touchstart', 'touchend']
      .forEach(function (type) {
        host.addEventListener(type, function (e) { e.stopPropagation(); });
      });
    host.addEventListener('keydown', function (e) {
      if (e.key === 'Escape' && !card.hidden) {
        card.hidden = true;
        chip.setAttribute('aria-expanded', 'false');
        chip.focus();
      }
    });

    /* ---------------- placement ---------------- */
    function place() {
      var offset = reserveCorner(cfg.corner, 21, PART);
      var vertical = 12 + offset;
      var c = cfg.corner;
      wrap.style.top = wrap.style.bottom = wrap.style.left = wrap.style.right = '';
      if (c.indexOf('bottom') === 0) {
        wrap.style.bottom = 'calc(' + vertical + 'px + env(safe-area-inset-bottom,0px))';
      } else {
        wrap.style.top = 'calc(' + vertical + 'px + env(safe-area-inset-top,0px))';
      }
      if (c.indexOf('right') > -1) {
        wrap.style.right = 'calc(12px + env(safe-area-inset-right,0px))';
      } else {
        wrap.style.left = 'calc(12px + env(safe-area-inset-left,0px))';
      }
    }

    // Usually <body>. A selector or element can be passed instead — used by the
    // docs demo to keep the badge inside its box.
    function resolveContainer() {
      var c = cfg.container;
      if (typeof c === 'string') c = document.querySelector(c);
      return c || document.body || document.documentElement;
    }

    function followFullscreen() {
      var fs = document.fullscreenElement || document.webkitFullscreenElement;
      var target = fs && !fs.contains(host) ? fs : resolveContainer();
      if (host.parentNode !== target) target.appendChild(host);
    }
    document.addEventListener('fullscreenchange', followFullscreen);
    document.addEventListener('webkitfullscreenchange', followFullscreen);

    function mount() {
      resolveContainer().appendChild(host);
      detect();
    }
    if (document.body) mount();
    else document.addEventListener('DOMContentLoaded', mount, { once: true });

    return {
      part: PART,
      version: PART_VERSION,
      config: cfg,
      /** The build info the badge resolved. */
      info: function () { return Object.assign({}, info, { env: env }); },
      /** Set the version by hand (e.g. after your own fetch). */
      set: function (v) { info.version = String(v); publish(); },
      destroy: function () { if (host.parentNode) host.parentNode.removeChild(host); },
    };
  }

  function optionsFromScript(el) {
    if (!el) return {};
    var d = el.dataset || {};
    var o = {};
    if (d.version) o.version = d.version;
    if (d.project) o.project = d.project;
    if (d.src) o.src = d.src === 'false' ? false : d.src;
    if (d.changelog) o.changelog = d.changelog;
    if (d.corner) o.corner = d.corner;
    if (d.theme) o.theme = d.theme;
    if (d.prefix !== undefined) o.prefix = d.prefix;
    if (d.env) o.env = d.env;
    if (d.container) o.container = d.container;
    if (d.showEnv === 'false') o.showEnv = false;
    if (d.expandable === 'false') o.expandable = false;
    return o;
  }

  var self = document.currentScript;
  var api = {
    part: PART,
    version: PART_VERSION,
    init: function (options) { return create(options); },
  };
  Outfitter.versionBadge = api;

  if (!self || self.dataset.auto !== 'false') {
    var instance = create(optionsFromScript(self));
    api.instance = instance;
    api.info = instance.info;
    api.set = instance.set;
  }
})();
